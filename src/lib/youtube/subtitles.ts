/**
 * YouTube Subtitle/Caption Fetcher (Supadata-powered)
 *
 * Fetches timestamped captions from YouTube via Supadata's transcript API.
 *
 * Why Supadata (replaces Apify pintostudio actor):
 * The pintostudio Apify actor was IP-blocked by YouTube — it would return
 * a SUCCEEDED run with `{ data: [] }` (empty) for videos that actually have
 * captions. Supadata uses its own rotating proxy infrastructure that YouTube
 * does not block, returning full transcripts consistently.
 *
 * API: https://api.supadata.ai/v1/youtube/transcript?videoId=XXX
 * Auth: x-api-key header
 * Response: { lang, availableLangs, content: [{ text, offset, duration }] }
 *   - offset and duration are in MILLISECONDS
 *
 * Pricing: 1 credit per transcript, 100 free/month, $10 per 1,000 extra (~$0.01/video)
 * Docs: https://docs.supadata.ai
 */

import { logQuota } from '@/lib/ai/usage-tracker';
import { fetchCaptionsBrightData } from './subtitles-brightdata';

// ─── Types ───────────────────────────────────────────────────────────────────

export interface CaptionSegment {
    text: string;
    start: number;    // Start time in seconds
    duration: number; // Duration in seconds
}

export interface CaptionResult {
    segments: CaptionSegment[];
    language: string;
    isAutoGenerated: boolean;
}

/**
 * Why did caption fetching fail?  Lets the pipeline distinguish
 * "this video genuinely has no captions" from "Supadata had a hiccup."
 */
export type CaptionFailureReason =
    | 'no_captions'        // Genuine — 404, 206, or empty content array
    | 'rate_limited'       // 429 — per-second request rate exceeded (retryable with backoff)
    | 'quota_exceeded'     // 429 — monthly plan credit quota exhausted (stop pipeline)
    | 'credits_exhausted'  // 402 — monthly credit limit hit
    | 'geo_restricted'     // 403 — video not available in Supadata's region
    | 'members_only'       // 403 — video requires channel membership
    | 'live_stream'        // 403 — live stream (no transcript available)
    | 'server_error'       // 500+ — Supadata infrastructure issue
    | 'timeout'            // AbortError — 60s exceeded
    | 'auth_error'         // 401 — bad API key (non-retryable)
    | 'parse_error'        // Non-JSON response body (CDN error page, etc.)
    | 'missing_api_key'    // SUPADATA_API_KEY env var not set
    | 'unknown';           // Catch-all

export interface CaptionFetchResult {
    success: boolean;
    data?: CaptionResult;                // populated when success=true
    failureReason?: CaptionFailureReason; // populated when success=false
    retryable: boolean;                  // true for transient failures
    message?: string;                    // human-readable error description
}

// ─── Caption Fetching ─────────────────────────────────────────────────────────

/**
 * Fetch timestamped captions for a YouTube video.
 *
 * Provider routing (2026-07, after Supadata cut its free tier to 100/mo):
 *   1. Bright Data (BRIGHTDATA_API_KEY set) — primary. Scrape-job API,
 *      ~$0.75–1.50 per 1,000 records.
 *   2. Supadata free tier — fallback ONLY on hard Bright Data infra failures
 *      (server_error/auth/parse), never on a genuine "no captions" and never
 *      on a TIMEOUT: a Bright Data timeout means the job is still queued on
 *      their side and the next attempt resumes the same snapshot (see
 *      subtitles-brightdata.ts) — falling back there was draining the free
 *      100/mo in days (measured 2026-07-09: 28% of jobs "timed out" while
 *      every one of them later completed). If the fallback itself fails,
 *      the ORIGINAL Bright Data failure is returned — so Supadata's
 *      quota_exceeded can never halt the pipeline.
 *
 * CAPTION_PROVIDER=supadata forces the fast direct path. Set on Firebase App
 * Hosting (interactive host): manual admin intakes run inside a 300–600s
 * request window that can't absorb a multi-minute Bright Data job, and the
 * occasional manual video fits easily in Supadata's free 100/month. The
 * Oracle batch pipelines leave it unset and get the cheap provider.
 *
 * @returns CaptionFetchResult indicating success/failure with a reason code.
 *          Callers should check `.retryable` to decide whether to retry or
 *          permanently mark the video as caption-less.
 */
export async function fetchCaptions(videoId: string): Promise<CaptionFetchResult> {
    if (process.env.CAPTION_PROVIDER !== 'supadata' && process.env.BRIGHTDATA_API_KEY) {
        const bd = await fetchCaptionsBrightData(videoId);
        // Trust Bright Data on success AND on a definitive "no captions".
        if (bd.success || bd.failureReason === 'no_captions') return bd;
        // Timeout = job still cooking at Bright Data; the retry resumes the
        // same snapshot. Don't spend a Supadata credit on it.
        if (bd.failureReason === 'timeout') return bd;

        if (process.env.SUPADATA_API_KEY) {
            console.warn(`[Captions] Bright Data failed (${bd.failureReason}) for ${videoId} — trying Supadata fallback`);
            const sd = await fetchCaptionsSupadata(videoId);
            if (sd.success) return sd;
            return bd; // fallback failed too — report the primary provider's failure
        }
        return bd;
    }
    return fetchCaptionsSupadata(videoId);
}

/**
 * Fetch timestamped captions via Supadata (legacy primary, now the fallback).
 *
 * Single HTTP call — no polling. Typical response time: 3–7 seconds.
 * Pricing: 1 credit per transcript, 100 free/month.
 */
export async function fetchCaptionsSupadata(videoId: string): Promise<CaptionFetchResult> {
    const apiKey = process.env.SUPADATA_API_KEY;
    if (!apiKey) {
        console.error('[Supadata] Missing SUPADATA_API_KEY environment variable');
        return { success: false, retryable: false, failureReason: 'missing_api_key', message: 'SUPADATA_API_KEY not set' };
    }

    const url = `https://api.supadata.ai/v1/youtube/transcript?videoId=${videoId}`;
    console.log(`[Supadata] Fetching transcript for ${videoId}...`);

    try {
        const controller = new AbortController();
        const timer = setTimeout(() => controller.abort(), 60000); // 60s timeout

        let res: Response;
        try {
            res = await fetch(url, {
                headers: { 'x-api-key': apiKey },
                signal: controller.signal,
            });
        } finally {
            clearTimeout(timer);
        }

        if (!res.ok && res.status !== 206) {
            const body = await res.text();
            if (res.status === 401) {
                console.error(`[Supadata] INVALID API KEY (401) for ${videoId} — check SUPADATA_API_KEY environment variable.`);
                return { success: false, retryable: false, failureReason: 'auth_error', message: 'Invalid Supadata API key (401)' };
            } else if (res.status === 402) {
                console.error(`[Supadata] PAYMENT REQUIRED (402) for ${videoId} — monthly credits exhausted.`);
                return { success: false, retryable: true, failureReason: 'credits_exhausted', message: 'Supadata monthly credits exhausted (402)' };
            } else if (res.status === 403) {
                // Parse 403 body to distinguish sub-reasons
                const bodyLower = body.toLowerCase();
                let reason403: CaptionFailureReason = 'geo_restricted';
                let label403 = 'Geo-restricted';

                if (bodyLower.includes('membership') || bodyLower.includes('members')) {
                    reason403 = 'members_only';
                    label403 = 'Members-only';
                } else if (bodyLower.includes('live stream') || bodyLower.includes('live_stream') || bodyLower.includes('livestream')) {
                    reason403 = 'live_stream';
                    label403 = 'Live stream';
                }

                console.log(`[Supadata] ${label403.toUpperCase()} (403) for ${videoId}: ${body.slice(0, 80)}`);
                return { success: false, retryable: false, failureReason: reason403, message: `${label403} (403): ${body.slice(0, 100)}` };
            } else if (res.status === 429) {
                // Distinguish quota exhaustion from per-second rate limiting
                // Supadata returns {"error":"limit-exceeded"} when monthly credits are gone
                let isQuotaExhausted = false;
                try {
                    const parsed = JSON.parse(body);
                    isQuotaExhausted = parsed?.error === 'limit-exceeded'
                        || parsed?.details?.toLowerCase().includes('plan usage limit');
                } catch { /* body wasn't JSON — treat as generic rate limit */ }

                if (isQuotaExhausted) {
                    console.error(`[Supadata] QUOTA EXCEEDED (429) for ${videoId} — monthly plan credits exhausted. STOP PIPELINE.`);
                    return { success: false, retryable: false, failureReason: 'quota_exceeded', message: `Supadata quota exceeded: ${body.slice(0, 100)}` };
                } else {
                    console.error(`[Supadata] RATE LIMITED (429) for ${videoId} — per-second request rate exceeded.`);
                    return { success: false, retryable: true, failureReason: 'rate_limited', message: `Supadata rate limited (429): ${body.slice(0, 100)}` };
                }
            } else if (res.status === 404) {
                console.log(`[Supadata] No captions available for ${videoId} (404)`);
                return { success: false, retryable: false, failureReason: 'no_captions', message: 'No captions available (404)' };
            } else if (res.status >= 500) {
                console.error(`[Supadata] SERVER ERROR (${res.status}) for ${videoId} — Supadata infrastructure issue.`);
                return { success: false, retryable: true, failureReason: 'server_error', message: `Supadata server error (${res.status}): ${body.slice(0, 100)}` };
            } else {
                console.error(`[Supadata] HTTP ${res.status} for ${videoId}: ${body}`);
                return { success: false, retryable: true, failureReason: 'unknown', message: `Unexpected HTTP ${res.status}: ${body.slice(0, 100)}` };
            }
        }

        // 206 = Supadata's "transcript-unavailable" — video exists but has no captions
        if (res.status === 206) {
            console.log(`[Supadata] Transcript unavailable for ${videoId} (206) — video has no captions.`);
            return { success: false, retryable: false, failureReason: 'no_captions', message: 'Transcript unavailable (206)' };
        }

        // Read body as text first — if Supadata's CDN returns an HTML error page with
        // a 200 status, res.json() would throw an ugly "Unexpected token '<'" error.
        const rawBody = await res.text();
        let data: { lang: string; availableLangs: string[]; content: Array<{ text: string; offset: number; duration: number; lang: string }> };
        try {
            data = JSON.parse(rawBody);
        } catch {
            console.error(`[Supadata] Non-JSON response for ${videoId} (HTTP ${res.status}): ${rawBody.slice(0, 150).replace(/\s+/g, ' ')}`);
            return { success: false, retryable: true, failureReason: 'parse_error', message: `Non-JSON response (HTTP ${res.status}): ${rawBody.slice(0, 80)}` };
        }

        const content = data?.content;
        if (!Array.isArray(content) || content.length === 0) {
            console.log(`[Supadata] No transcript content for ${videoId} (lang: ${data?.lang})`);
            return { success: false, retryable: false, failureReason: 'no_captions', message: `Empty content array (lang: ${data?.lang})` };
        }

        // Supadata returns offset + duration in milliseconds — convert to seconds
        const segments: CaptionSegment[] = content
            .map(seg => ({
                text: decodeHtmlEntities((seg.text || '').trim()),
                start: (seg.offset ?? 0) / 1000,
                duration: (seg.duration ?? 0) / 1000,
            }))
            .filter(seg => seg.text.length > 0);

        console.log(`[Supadata] ✅ ${segments.length} segments for ${videoId} (lang: ${data.lang})`);

        // 1 credit consumed per successful transcript fetch.
        void logQuota({ provider: 'supadata', operation: 'supadata.transcript', quantity: 1, metadata: { videoId } });

        return {
            success: true,
            retryable: false,
            data: {
                segments,
                language: data.lang || 'en',
                isAutoGenerated: true, // Supadata doesn't distinguish; assume auto
            },
        };
    } catch (error: any) {
        if (error?.name === 'AbortError') {
            console.error(`[Supadata] Timeout (60s) fetching captions for ${videoId}`);
            return { success: false, retryable: true, failureReason: 'timeout', message: 'Request timed out after 60s' };
        } else {
            console.error(`[Supadata] Error fetching captions for ${videoId}:`, error?.message || error);
            return { success: false, retryable: true, failureReason: 'unknown', message: error?.message || String(error) };
        }
    }
}

// ─── Internal Helpers ─────────────────────────────────────────────────────────

/**
 * Decode common HTML entities found in YouTube caption text.
 */
function decodeHtmlEntities(text: string): string {
    return text
        .replace(/&amp;/g, '&')
        .replace(/&lt;/g, '<')
        .replace(/&gt;/g, '>')
        .replace(/&quot;/g, '"')
        .replace(/&#39;/g, "'")
        .replace(/&apos;/g, "'")
        .replace(/\n/g, ' ')
        .trim();
}
